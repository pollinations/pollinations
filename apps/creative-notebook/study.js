export const defaults = {
    subject: "A greenhouse grown from discarded circuit boards",
    medium: "cyanotype",
    model: "tongyi-mai/z-image-turbo",
    seed: 42,
};

export function parametersFor({ subject, medium, model, seed }) {
    if (!subject.trim() || !model.trim()) {
        throw new Error("Enter a subject and image model.");
    }
    const number = Number(seed);
    if (!Number.isInteger(number) || number < 0 || number > 2147483647) {
        throw new Error("Seed must be an integer from 0 to 2147483647.");
    }
    return {
        prompt: `${subject.trim()}. ${medium}, botanical study, no lettering.`,
        model: model.trim(),
        seed: number,
        width: 768,
        height: 768,
    };
}

export function imageUrl(parameters) {
    const { prompt, model, seed, width, height } = parameters;
    const url = new URL(
        `https://gen.pollinations.ai/image/${encodeURIComponent(prompt)}`,
    );
    url.search = new URLSearchParams({ model, seed, width, height }).toString();
    return url.href;
}

