// Explicit field selection keeps request headers and credentials out of exports.
export function exportStudy({ parameters, images }) {
    const { prompt, model, seed, width, height } = parameters;
    return {
        images: images.map(({ url, caption }) => ({ url, caption })),
        parameters: { prompt, model, seed, width, height },
        source: ["notebook.html", "study.js", "package.json", "study.test.js"],
    };
}
