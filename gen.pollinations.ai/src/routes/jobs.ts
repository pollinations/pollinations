import { type Context, Hono } from "hono";
import { describeRoute } from "hono-openapi";
import type { GenerationJobStatus } from "@/durable-objects/GenerationCoordinator.ts";
import type { Env } from "@/env.ts";
import { auth } from "@/middleware/auth.ts";
import {
    type GenerationErrorSnapshot,
    replayFailedResponse,
} from "@/middleware/generation-deduplication.ts";
import { edgeRateLimit } from "@/middleware/rate-limit-edge.ts";
import { getCachedResponse } from "@/utils/text-cache.ts";

// Job ids are the coordinator names: SHA-256 hex of `storage:key`.
const JOB_ID_PATTERN = /^[a-f0-9]{64}$/;

function jobNotFound(id: string): Response {
    return Response.json(
        {
            error: "not_found",
            message:
                "Unknown job. It may have expired (results are collectable " +
                "for 24 hours) or was started by another account.",
            id,
        },
        { status: 404 },
    );
}

function statusResponse(id: string, status: GenerationJobStatus): Response {
    if (status.status === "processing") {
        return Response.json(
            {
                id,
                status: status.status,
                urls: { result: `/v1/jobs/${id}/result` },
            },
            {
                status: 200,
                headers: { "Retry-After": "2" },
            },
        );
    }
    if (status.status === "failed") {
        return Response.json({
            id,
            status: status.status,
            error: {
                httpStatus: status.error?.httpStatus,
                message: status.error
                    ? new TextDecoder()
                          .decode(status.error.body.slice(0, 4096))
                          .trim()
                    : undefined,
            },
        });
    }
    return Response.json({
        id,
        status: status.status,
        urls: { result: `/v1/jobs/${id}/result` },
    });
}

async function readCachedResult(
    c: Context<Env>,
    storage: "media" | "text",
    key: string,
): Promise<Response | null> {
    if (storage === "media") {
        return c.env.MEDIA.get(key);
    }
    // The text cache adapter reconstructs headers from R2 object metadata.
    return getCachedResponse(c, key);
}

// Only the account that started a job can read it. Auth runs first on every
// route; the coordinator enforces ownership by caller id.
export const jobRoutes = new Hono<Env>()
    .use("*", edgeRateLimit)
    .use("*", auth())
    .get(
        "/v1/jobs/:id",
        describeRoute({
            tags: ["⏳ Async Jobs"],
            summary: "Get Generation Job Status",
            description: [
                "Status of a generation job submitted with `Prefer: respond-async`.",
                "",
                "Poll this endpoint after the submit call returns a job id. `status` is one of:",
                "- `queued` / `processing` — still running (check the `Retry-After` header)",
                "- `succeeded` — the result is ready at `GET /v1/jobs/{id}/result`",
                "- `failed` — the `error` object carries the reason",
                "",
                "Only the account that started the job (or joined it by submitting the identical request) can read it. Settled jobs stay collectable for 24 hours.",
            ].join("\n"),
            responses: {
                200: {
                    description:
                        "Current job status; include a Retry-After header while running",
                },
                401: { description: "Authentication required" },
                404: { description: "Unknown or expired job" },
            },
        }),
        async (c) => {
            const id = c.req.param("id");
            if (!JOB_ID_PATTERN.test(id)) return jobNotFound(id);
            const caller = c.var.auth.requireUser().id;
            const stub = c.env.GENERATION_COORDINATOR.getByName(id);
            const status = (await stub.jobStatus(
                caller,
            )) as GenerationJobStatus | null;
            return status ? statusResponse(id, status) : jobNotFound(id);
        },
    )
    .get(
        "/v1/jobs/:id/result",
        describeRoute({
            tags: ["⏳ Async Jobs"],
            summary: "Get Generation Job Result",
            description: [
                "The generated bytes of a completed job — image, video, audio, 3D or text, served from the durable result cache.",
                "",
                "Returns `425 Too Early` with a `Retry-After` header while the job is still running. Failed jobs replay the captured error response. Only the account that started the job can read it.",
            ].join("\n"),
            responses: {
                200: { description: "Generated content" },
                401: { description: "Authentication required" },
                404: { description: "Unknown or expired job" },
                425: {
                    description:
                        "Job still processing — retry after Retry-After",
                },
            },
        }),
        async (c) => {
            const id = c.req.param("id");
            if (!JOB_ID_PATTERN.test(id)) return jobNotFound(id);
            const caller = c.var.auth.requireUser().id;
            const stub = c.env.GENERATION_COORDINATOR.getByName(id);
            const status = (await stub.jobStatus(
                caller,
            )) as GenerationJobStatus | null;
            if (!status) return jobNotFound(id);
            if (status.status === "processing") {
                return Response.json(
                    { id, status: status.status },
                    { status: 425, headers: { "Retry-After": "2" } },
                );
            }
            if (status.status === "failed") {
                return replayFailedResponse(status.error ?? unknownError());
            }
            const result = await readCachedResult(
                c,
                status.cache.storage,
                status.cache.key,
            );
            if (!result) return jobNotFound(id);
            result.headers.set("X-Job-Id", id);
            return result;
        },
    );

function unknownError(): GenerationErrorSnapshot {
    return {
        httpStatus: 502,
        headers: [["content-type", "text/plain; charset=UTF-8"]],
        body: new TextEncoder().encode("Generation failed"),
    };
}
