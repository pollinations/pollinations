// Regenerates src/ui/extApps.generated.js from the self-contained browser
// bundle that @modelcontextprotocol/ext-apps ships. Run after upgrading it:
//   node scripts/build-ext-apps.js
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const OUTPUT = new URL("../src/ui/extApps.generated.js", import.meta.url);

// A card inlines the SDK in its own <script type="module">, which nothing can
// import from, so the bundle's export list becomes a local ExtApps object.
export async function buildExtAppsScript() {
    const bundle = await readFile(
        fileURLToPath(
            import.meta.resolve("@modelcontextprotocol/ext-apps/app-with-deps"),
        ),
        "utf8",
    );
    const exportList = bundle.match(/export\s*\{([^}]*)\};?\s*$/);
    if (!exportList || /<\/script/i.test(bundle)) {
        throw new Error("Unexpected @modelcontextprotocol/ext-apps bundle");
    }
    const names = exportList[1].replace(/([\w$]+) as ([\w$]+)/g, "$2:$1");
    return `${bundle.slice(0, exportList.index)}const ExtApps={${names}};`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const script = await buildExtAppsScript();
    await writeFile(
        OUTPUT,
        "// Generated by scripts/build-ext-apps.js. Do not edit.\n" +
            `export const EXT_APPS_SCRIPT = ${JSON.stringify(script)};\n`,
    );
}
