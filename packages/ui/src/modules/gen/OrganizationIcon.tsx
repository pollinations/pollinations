export function organizationLogo(name?: string): string | undefined {
    return name && Object.hasOwn(logos, name) ? logos[name] : undefined;
}

export function LogoMask({
    src,
    className = "polli:size-8",
}: {
    src: string;
    className?: string;
}) {
    const mask = `url(${JSON.stringify(src)}) center / contain no-repeat`;
    return (
        <span
            aria-hidden="true"
            className={`polli:inline-block polli:bg-current ${className}`}
            style={{ mask, WebkitMask: mask }}
        />
    );
}

export function OrganizationIcon({
    name,
    className,
}: {
    name: string;
    className?: string;
}) {
    const src = organizationLogo(name);
    return src ? <LogoMask src={src} className={className} /> : null;
}
